using System.Net;
using System.Text;
using System.Text.Json;
using AimPark.API.Reports;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace AimPark.API.Controllers
{
    /// <summary>
    /// What the QR code on a printed report opens: the report's number, who
    /// made it, and the figures it showed, as the system recorded them.
    /// </summary>
    /// <remarks>
    /// Public on purpose. The person checking a printout (a dean, an auditor)
    /// has no AimPark account, and is holding the paper on a phone. The link
    /// carries a random 128-bit token rather than the report number, so it
    /// cannot be guessed, and the page shows totals only, never a name.
    /// </remarks>
    [ApiController]
    [Route("api/reports/verify")]
    [AllowAnonymous]
    public class ReportVerifyController(ReportPdfService pdfs) : ControllerBase
    {
        private record Figure(string Label, string Value);

        [HttpGet("{token}")]
        public async Task<ContentResult> Get(string token, CancellationToken ct)
        {
            var report = token.Length is > 0 and <= 64 ? await pdfs.FindByTokenAsync(token, ct) : null;

            if (report is null)
            {
                return Page(404, "Report not found",
                    "<p class=\"bad\">No AimPark report matches this code.</p>" +
                    "<p>The code may have been copied wrongly, or the paper did not come from AimPark.</p>");
            }

            var figures = JsonSerializer.Deserialize<List<Figure>>(report.KeyFiguresJson,
                new JsonSerializerOptions(JsonSerializerDefaults.Web)) ?? [];

            var period = report.PeriodFrom is DateOnly f && report.PeriodTo is DateOnly t
                ? PdfLayout.Period(f, t)
                : $"As of {PdfLayout.Stamp(report.GeneratedAt)}";

            var html = new StringBuilder();
            html.Append("<p class=\"ok\">This is a genuine AimPark report.</p>");
            html.Append("<table>");
            Row(html, "Report no.", report.Number);
            Row(html, "Report", report.Title);
            Row(html, "Covers", period);
            Row(html, "Generated by", report.GeneratedByName);
            Row(html, "Generated on", PdfLayout.Stamp(report.GeneratedAt));
            html.Append("</table>");

            html.Append("<h2>Figures on the report</h2><table>");
            foreach (var fig in figures) Row(html, fig.Label, fig.Value);
            html.Append("</table>");

            html.Append("<p class=\"muted\">Compare these with the printed copy. If any figure is different, " +
                        "the paper was changed after it was printed. These are the figures as of the moment " +
                        "the report was made; later payments do not change them.</p>");

            return Page(200, $"Report {report.Number}", html.ToString());
        }

        private static void Row(StringBuilder html, string label, string value) =>
            html.Append("<tr><th>").Append(WebUtility.HtmlEncode(label))
                .Append("</th><td>").Append(WebUtility.HtmlEncode(value)).Append("</td></tr>");

        private static ContentResult Page(int status, string title, string body) => new()
        {
            StatusCode = status,
            ContentType = "text/html; charset=utf-8",
            Content = $$"""
                <!doctype html>
                <html lang="en"><head>
                <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
                <meta name="robots" content="noindex">
                <title>{{WebUtility.HtmlEncode(title)}} · AimPark</title>
                <style>
                  body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;padding:24px 16px;color:#1f1f1d;background:#f6f5f1}
                  main{max-width:520px;margin:0 auto;background:#fff;border:1px solid #e2e0d8;border-radius:12px;padding:20px}
                  h1{font-size:18px;margin:0 0 4px} h2{font-size:15px;margin:20px 0 6px}
                  .sub{color:#5f5e5a;font-size:13px;margin:0 0 16px}
                  table{width:100%;border-collapse:collapse;font-size:14px}
                  th{text-align:left;font-weight:500;color:#5f5e5a;padding:6px 8px 6px 0;vertical-align:top;width:45%}
                  td{padding:6px 0;text-align:right} tr{border-bottom:1px solid #eeece6}
                  .ok{background:#eaf3de;color:#27500a;padding:10px 12px;border-radius:8px;font-weight:500}
                  .bad{background:#fcebeb;color:#791f1f;padding:10px 12px;border-radius:8px;font-weight:500}
                  .muted{color:#5f5e5a;font-size:13px;line-height:1.5}
                </style></head>
                <body><main>
                <h1>AimPark report check</h1>
                <p class="sub">AimPark Smart Parking System</p>
                {{body}}
                </main></body></html>
                """
        };
    }
}
